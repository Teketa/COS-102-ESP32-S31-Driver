#!/usr/bin/env python3
"""Embed the web UI (src/web/index.html) into src/web_index.c as a C array.

Runs automatically before every PlatformIO build (extra_scripts = pre:...),
so editing index.html and rebuilding is all you need. The file is only
rewritten when the HTML actually changed, so it doesn't force recompiles.

Can also be run by hand:  python3 tools/gen_web.py
"""
import os
import pathlib


def _project_root():
    try:                                  # running inside PlatformIO / SCons
        Import("env")                     # noqa: F821  (SCons builtin)
        return pathlib.Path(env.subst("$PROJECT_DIR"))  # noqa: F821
    except NameError:                     # running standalone
        return pathlib.Path(os.path.abspath(__file__)).parent.parent


def generate(root):
    src = root / "src" / "web" / "index.html"
    dst = root / "src" / "web_index.c"
    data = src.read_bytes()
    lines = ["// GENERATED by tools/gen_web.py from src/web/index.html -- do not edit.",
             "#include <stddef.h>", "",
             "const char web_index_html[] = {"]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines += ["};", f"const size_t web_index_html_len = {len(data)};", ""]
    out = "\n".join(lines)
    if not dst.exists() or dst.read_text() != out:
        dst.write_text(out)
        print(f"gen_web: {src.name} ({len(data)} bytes) -> {dst.relative_to(root)}")


generate(_project_root())
