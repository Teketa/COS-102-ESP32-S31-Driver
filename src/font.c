#define FONT_COUNT (int)(sizeof(FONT) / 5)

// Danish extras, same format.
static const uint8_t DK[6][5] = {
    {0x7C,0x0A,0x7F,0x49,0x49},   // Æ
    {0x3E,0x51,0x49,0x45,0x3E},   // Ø (O with bar)
    {0x7C,0x13,0x12,0x13,0x7C},   // Å (A with ring hint)
    {0x38,0x54,0x3C,0x54,0x58},   // æ
    {0x38,0x64,0x54,0x4C,0x38},   // ø
    {0x20,0x55,0x56,0x55,0x78},   // å
};

uint32_t utf8_next(const char **s)
{
    const unsigned char *p = (const unsigned char *)*s;
    if (!*p) return 0;
    uint32_t cp;
    if (*p < 0x80) { cp = *p; p += 1; }
    else if ((*p & 0xE0) == 0xC0 && p[1]) { cp = ((*p & 0x1F) << 6) | (p[1] & 0x3F); p += 2; }
    else if ((*p & 0xF0) == 0xE0 && p[1] && p[2]) {
        cp = ((*p & 0x0F) << 12) | ((p[1] & 0x3F) << 6) | (p[2] & 0x3F); p += 3;
    } else { cp = '?'; p += 1; }
    *s = (const char *)p;
    return cp;
}

const uint8_t *font_glyph(uint32_t cp)
{
    switch (cp) {
    case 0xC6: return DK[0];   // Æ
    case 0xD8: return DK[1];   // Ø
    case 0xC5: return DK[2];   // Å
    case 0xE6: return DK[3];   // æ
    case 0xF8: return DK[4];   // ø
    case 0xE5: return DK[5];   // å
    default: break;
    }
    if (cp < 32 || cp > 126) cp = '?';
    int idx = (int)cp - 32;
    if (idx >= FONT_COUNT) idx = '?' - 32;
    return FONT[idx];
}

int font_text_len(const char *s)
{
    int n = 0;
    while (*s) { utf8_next(&s); n++; }
    return n;
}

int font_text_width(const char *s)
{
    int n = font_text_len(s);
    return n ? n * FONT_ADVANCE - FONT_GAP : 0;
}
